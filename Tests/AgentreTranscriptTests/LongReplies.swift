# 操作系统原理通论

## 第一章 操作系统的概念、历史与结构

### 1.1 什么是操作系统

操作系统(Operating System, OS)是计算机系统中紧贴硬件的第一层系统软件，它向下管理并抽象处理器、内存、外设等物理资源，向上为应用程序和用户提供一个便捷、高效、安全、可扩展的运行环境与服务的集合。可以从三个视角理解它：资源管理者的视角——操作系统是资源分配器，负责管理 CPU 时间、内存空间、存储容量和 I/O 设备，在相互竞争的程序之间协调与仲裁；控制程序的视角——操作系统是用户程序与底层硬件之间的中介，控制用户程序的执行，防止错误和计算机的不当使用；抽象提供者的视角——也许是最深刻的视角，操作系统的本质工作是抽象：把丑陋复杂的硬件接口改造成干净优雅的抽象，如进程、文件、虚拟内存、套接字。程序员几乎从不直接与磁盘扇区、页表、中断控制器打交道，他们面对的是 fork()、read()、mmap() 这些整洁的概念。

操作系统的设计目标可以归纳为四点：方便性(让计算机更易用)、有效性(提高资源利用率)、可扩展性(方便增加新功能而不扰乱原有功能)、开放性/可移植性(遵循标准，使不同厂商的系统与软件能互操作)。这四者之间常有张力，例如为了方便而做的抽象可能牺牲有效性，不同历史时期的操作系统正是在这些目标之间寻找不同的平衡点。

### 1.2 发展历史

操作系统随硬件演进，大致经历了几个阶段。手工操作阶段(1940 年代末至 50 年代初)没有操作系统，程序员用插线板和开关直接操作机器，CPU 常常在一批人上下机交接时大量空转。单道批处理系统(1950 年代)将作业成批提交，由监督程序(monitor)依次调入内存执行，消除了人工装磁带的等待，但作业串行执行，I/O 慢速设备与 CPU 快速计算之间的矛盾突出——CPU 在等待打孔机打印时完全闲置。多道程序设计(multiprogramming,1960 年代初)是划时代的思想：在内存中同时保留多个作业，当一个作业进行 I/O 时，CPU 立即切换去执行另一个作业，只要作业搭配得当，CPU 与设备都能保持忙碌，吞吐量大幅提升。多道程序要求操作系统解决内存保护、作业调度、设备管理等新问题，现代操作系统的雏形由此形成。分时系统(time-sharing,如 1961 年的 CTSS 与后来的 Multics、UNIX)把 CPU 时间切成小的时间片轮流分配给多个联机终端用户，每个用户都感觉自己在独占一台机器，交互式计算成为现实，这对调度响应性和内存共享提出了更高要求。此后，随着超大规模集成电路与个人计算机兴起，操作系统走向大众(CP/M、MS-DOS、Mac OS、Windows),并逐步融合大型机的技术(虚拟内存、多任务、多用户)；1991 年 Linus Torvalds 发布 Linux 内核，与 GNU 工具链和 POSIX 标准结合，成为服务器、嵌入式与云计算领域的主导系统；移动时代则出现了 iOS 与 Android 这类以 Linux 或类 Unix 微内核为基础的系统。今天，操作系统原理仍以 UNIX、Linux、Windows 三大体系为主要参照。

### 1.3 操作系统的特征

现代操作系统有四个基本特征。并发(concurrency):宏观上多个程序同时运行，微观上多个程序在单个 CPU 上交替执行(或真正同时运行于多核)。并发与并行(parallelism)不同：并行需要多个物理处理部件同时工作，并发是逻辑上的“同时”，通过 CPU 切换实现。并发是并行的泛化，是操作系统复杂性的根源。共享(sharing):系统资源可供多个并发进程共同使用，分为互斥共享(打印机等资源一段时间内只允许一个进程使用)与同时共享(磁盘、可重入代码等允许多个进程同时访问)。并发与共享互为存在条件：没有并发就无所谓共享的冲突，没有资源共享的抽象，并发也无意义。虚拟(virtuality):通过某种技术把物理实体变为逻辑对应物——CPU 虚拟为多个“虚 CPU”(进程)，物理内存虚拟为地址空间，一块磁盘虚拟为无数文件与目录，一台机器虚拟为多台(虚拟机)。异步(asynchrony):进程以不可预知的速度推进，“走走停停”，可能被中断、被抢占、被换出，但只要运行环境相同，每次执行的结果必须一致，这就是进程的“可再现性”，由同步机制保证。

### 1.4 内核体系结构

操作系统核心部分的组织方式主要有几类。单体内核(monolithic kernel):整个系统作为一组过程集合链接成一个大内核程序运行在内核态，各模块互相调用、共享数据，Linux 是典型代表。优点是模块间调用就是函数调用，开销小、效率高；缺点是结构不清晰，一处错误可能波及全局，扩展维护困难。Linux 通过可加载模块(LKM)机制部分缓解了僵化。微内核(microkernel):只把最基本的功能——进程间通信(IPC)、基本调度、底层内存管理——留在内核，其余(文件系统、设备驱动、网络协议栈)都作为用户态服务进程实现，代表有 Mach、QNX、L4 系列、MINIX 与 seL4。优点是结构清晰、可靠性高(单个服务崩溃不致整机崩溃)、便于形式化验证；缺点是跨模块协作需要频繁的 IPC 与地址空间切换，性能开销大，历史上著名的 Tanenbaum–Torvalds 之争(1992 年)正是围绕这一取舍展开。分层结构、外核(exokernel)、客户/服务器与虚拟机监视器(VMM) 是其他有影响的组织方式。无论何种结构，现代 CPU 都提供内核态(管态)与用户态(目态) 两种执行模式：特权指令(直接 I/O、页表基址修改、关中断等)只允许在内核态执行，用户程序请求内核服务必须通过系统调用(system call) 这一受控入口，由陷入(trap)指令完成模式切换。这一硬件机制是操作系统保护功能的基石，所谓“操作系统是中断驱动的”——系统调用、外设中断、异常构成了内核获取控制权的全部途径。

## 第二章 进程与线程

### 2.1 进程的概念

进程(process)是程序在一个数据集合上的运行过程，是系统进行资源分配和调度的独立单位。必须区分程序与进程：程序是静态的指令与数据的集合，是存放在磁盘上的可执行文件；进程是动态的，有诞生(创建)、活动(调度、执行)、消亡(终止)的生命周期，还具有并发性——同一程序同时运行三次，产生三个不同的进程。进程的组成包括：程序代码(text 段)、数据(全局变量、堆)、栈(函数调用帧、局部变量)、以及内核为管理它而维护的数据结构——进程控制块(Process Control Block, PCB)。PCB 是进程存在的唯一标志，内容涵盖进程标识符(PID)、处理器状态(程序计数器、寄存器快照)、调度信息(状态、优先级、已等待时间)、内存管理信息(页表基址、地址空间描述)、I/O 与文件信息(打开文件表、分配的设备)及记账信息。所有 PCB 用就绪队列、阻塞队列等链表组织起来，调度器实质上就是对这些队列的操纵。切换进程时保存与恢复的现场信息称为上下文(context),切换动作即上下文切换，它本身不做任何计算，是纯粹的开销，耗时从几微秒到几十微秒不等，这也是把进程切分得过细会得不偿失的原因。

### 2.2 进程状态与转换

进程在其生命周期中在几个状态间流转：运行态(正在 CPU 上执行)、就绪态(具备运行条件，只等 CPU)、阻塞态/等待态(因等待某事件如 I/O 完成、锁释放而暂停执行)。经典五态模型再加上创建态与终止态构成七态模型。关键转换包括：运行→就绪(时间片用完或被更高优先级进程抢占)；运行→阻塞(主动等待事件，是进程自身的同步行为)；阻塞→就绪(所等事件发生，由中断或其他进程唤醒——注意不能直接转为运行，必须先排队)；就绪→运行(被调度器选中)。在内存紧张引入挂起(suspend)机制后，进程还可以被换出到磁盘交换区，形成活动就绪、静止就绪、活动阻塞、静止阻塞等更细的状态。Linux 实现上用 TASK_RUNNING(同时涵盖就绪与运行)、TASK_INTERRUPTIBLE/TASK_UNINTERRUPTIBLE(可/不可被信号打断的睡眠)、TASK_STOPPED、TASK_ZOMBIE 等状态，其中僵尸态是进程已终止但 PCB 尚未被父进程 wait() 回收的状态，长期堆积僵尸进程会耗尽进程表资源。

### 2.3 进程控制

进程控制原语包括创建、终止、阻塞、唤醒、切换，它们由内核通过原语(primitive)实现——原语是执行期间不允许中断的原子操作，通过关中断或锁实现，以保证状态转换的一致性。UNIX 的进程创建采用独特的 fork/exec 模型:fork() 将父进程完整复制一份得到子进程(现代实现采用写时复制 copy-on-write,仅复制页表而不复制内存页，使 fork 极为廉价)，子进程随后通常调用 exec() 载入新程序映像替换自身代码与数据，再由父进程 wait()/waitpid() 收尸并获取退出状态。这一“复制再替换”的设计把“创建执行新程序”拆成两个正交原语，得以支持输入输出重定向、管道等优雅组合，是 UNIX 哲学的典范。进程间因此形成父子树：UNIX 的孤儿进程在父进程死后被 init/systemd(PID 1)收养。Windows 则提供 CreateProcess 一步完成创建与加载。

### 2.4 线程

进程有两个正交的角色：资源分配单位(地址空间、文件、设备)与调度执行单位。线程(thread)就是把这两者拆开：线程是 CPU 调度的基本单位，同一进程内的多个线程共享代码段、数据段、堆、打开文件与信号处理函数，但各自拥有独立的寄存器组、栈与程序计数器，以及内核为线程维护的线程控制块(TCB)。线程的优势：创建与切换开销小——同进程线程切换不更换地址空间，免去页表切换与缓存污染；通信便捷——共享地址空间使数据交换无需内核 IPC;并发性——在多核上真正并行，在单核上交错并发；响应性——一个线程阻塞时同进程其他线程仍可执行。典型的浏览器为每个标签页、每个渲染实例建立进程(隔离崩溃)，而每个页面内部又用多个线程分别处理解析、布局、脚本、网络。线程按管理者的不同分为内核级线程(由内核创建、调度、撤销，如 Linux 的 NPTL;线程阻塞不影响其他线程，但切换需陷入内核)与用户级线程(由用户空间线程库管理，内核不可见；切换极快、可定制调度，但一旦某线程发起阻塞系统调用，整个进程都会被内核置为阻塞，且无法利用多核)。多线程模型描述用户线程与内核线程的映射关系：多对一(效率高但并发受限)、一对一(Linux、Windows 采用，真正并行，代价是内核线程数量多)、多对多(混合式，如历史上的 Scheduler Activations 与一些 Go runtime 之前的模型)。

现代语言运行时流行的协程/绿色线程(goroutine、async/await 任务)本质是用户级线程思想的复兴：由运行时库在用户空间以极低成本调度，配以非阻塞 I/O 多路复用(epoll/kqueue/IOCP)避开“一个线程阻塞拖垮全进程”的陷阱，从而以少量内核线程承载海量并发任务——这是操作系统线程模型与语言运行时协作演进的最佳例证。此外需注意 Linux 的独特术语：内核的调度实体自 2.6 起从进程改为线程(称为 task),clone() 系统调用通过标志位精细控制子任务与父任务共享哪些资源，从而统一实现 fork、线程创建等多种语义，体现了“机制与策略分离”的设计智慧。

## 第三章 处理器调度

### 3.1 调度的层次与目标

处理器调度分为三级：高级调度(作业调度) 决定把外存后备队列中的哪些作业调入内存、建立进程，控制多道程序度(degree of multiprogramming);中级调度(内存调度) 负责把暂时不能运行的进程换出到外存(挂起)或换回，以平滑内存压力、提高吞吐；低级调度(进程/线程调度) 决定就绪队列中的哪个任务下一个获得 CPU,是频率最高(毫秒级甚至更短)、对系统体感影响最直接的调度。不同系统的调度目标不同：批处理系统追求吞吐量高、周转时间短、CPU 利用率高；交互式系统追求响应时间快、公平性；实时系统则必须满足截止时间(deadline),分为硬实时(错过即灾难，如飞控、ABS)与软实时(偶尔错过可容忍，如视频播放)。衡量指标包括周转时间(提交到完成)、带权周转时间(周转/实际运行)、响应时间(提交到首次响应)、等待时间与公平性。这些目标彼此冲突——为最短作业服务可以最小化平均周转时间，却让长作业饿死；追求交互响应的频繁切换又增加上下文切换开销。

### 3.2 经典调度算法

先来先服务(FCFS) 按到达顺序服务，实现最简单、非抢占，但平均周转时间差，且有护航效应(convoy effect):一个长作业率领一队短作业缓缓前进，短作业被迫久等。短作业优先(SJF)/ 短进程优先(SPF) 平均周转时间最优(可证明)，但作业长度难以预知(需指数平均预测)，且长作业可能无限饥饿；其抢占版本最短剩余时间优先(SRTF) 在新任务到达时比较剩余时间。高响应比优先(HRRN) 是 FCFS 与 SJF 的折中：响应比 =(等待+要求服务时间)/要求服务时间，等待越久响应比越高，兼顾长短作业且无饥饿，代价是每次调度需计算所有作业的响应比。时间片轮转(RR) 是分时系统的基石：就绪队列成环，每个进程运行一个时间片(quantum,典型 10–100ms)后被抢占排到队尾。时间片大小的选择是艺术：太大退化为 FCFS,交互响应变差；太小则上下文切换开销占比过高，CPU 有效做功比例下降。优先级调度 为每个进程赋优先级，可抢占或非抢占，灵活通用，但低优先级进程可能饥饿，解法是老化(aging):随等待时间动态提升优先级。多级队列调度 把就绪进程按类型(前台交互、后台批处理)分成多个队列，队列间采用固定优先级或时间片比例分配。多级反馈队列(MLFQ) 是集大成者：设置多个优先级递减、时间片递增的队列，新进程进入最高队列，用完该级时间片便降级，长作业逐级下沉最终以长片运行，同时若某进程在低层等待很久则提升其优先级，从而无须预知作业长度即可同时逼近 SJF 的周转性能与交互响应，传统 UNIX 与 Windows 均是其变体。

### 3.3 实时调度与 Linux 调度器

实时调度理论以周期性任务模型为基础：每个任务有周期 T、最坏执行时间 C、截止时间 D,可调度条件为 ΣC/T ≤ 1(单核)。经典算法：速率单调(RM) 静态优先级，周期越短优先级越高，可调度利用率上界约 0.693(n→∞);最早截止时间优先(EDF) 动态优先级，截止最近者先执行，理论利用率可达 100%,但过载时行为突变。现代实时系统还发展出优先级天花板、时间触发架构等。Linux 调度器经历了 O(n) 的传统调度器、O(1) 调度器、完全公平调度器 CFS(Completely Fair Scheduler,用红黑树按 vruntime 虚拟运行时间组织任务，以“理想公平 CPU”模型按权重比例分配时间，nice 值映射为权重)，直到 6.6 版本引入 EEVDF(Earliest Eligible Virtual Deadline First)取代 CFS,兼顾公平性与延迟保障。Linux 同时以 SCHED_FIFO/SCHED_RR 实时类满足 POSIX 实时需求，并以 cgroups 的 cpu controller 支撑容器化环境下的资源配额。多核调度还需考虑亲和性(affinity)——尽量让任务留在同一 CPU 以利用缓存热度，以及负载均衡——周期性或在调度点把任务从繁忙核迁往空闲核，以及为降低功耗的 big.LITTLE 大小核调配。

## 第四章 进程同步与互斥

### 4.1 竞争条件与临界区

并发进程共享数据时会出现竞争条件(race condition):结果取决于进程执行的相对时序。经典例子是两个进程同时执行 counter++——这条高级语句由“读、加、写”三条指令构成，交错执行会丢失一次增量。每个进程访问共享资源的代码段称为临界区(critical section),解决竞争条件的要求是 1965 年 Dijkstra 学生提出的经典准则：空闲让进(无人在临界区时应立即允许进入)、忙则等待(已有进程在内则他人必须等待)、有限等待(申请者必须在有限时间内进入，不能饿死)、让权等待(进不去时应释放 CPU,避免忙等)。历史上曾出现软件方案如 Dekker 算法与 Peterson 算法(两进程，用标志与谦让变量巧妙组合，Peterson 算法以两行代码的对称优雅著称)，但纯软件方案在编译器重排与乱序执行面前不再可靠，需要硬件栅栏配合；硬件方案则有中断开关(只适合单核内核态)、测试并设置 TAS/交换指令、比较并交换 CAS、取加指令 fetch-and-add 等原子指令。原子指令自旋忙等浪费 CPU 且在单核上必须配合内核让权，于是操作系统在其上构建了既能忙等互斥又能在争用时睡眠的高级原语。

### 4.2 互斥锁、信号量与管程

互斥锁(mutex lock) 是最基本的抽象：acquire/release 之间的代码构成临界区，实现上通常以 CAS 自旋快速路径 + 失败后陷入内核睡眠的组合(如 Linux 的 futex 设计，把竞争激烈才付系统调用代价做到极致)。信号量(semaphore) 由 Dijkstra 提出，是整型变量加两个原子操作：P(wait/proberen,测试并减，值≤0 则阻塞)与 V(signal/verhogen,加一并唤醒等待者)。计数信号量初值可为任意非负数，表达资源配额(初值 N 即允许 N 个进程同时进入或代表 N 个资源)；互斥信号量初值为 1,即互斥锁。信号量还能直接表达同步约束：P0 要等 P0 完成某事才能继续，则设初值为 0 的信号量，一方 V 另一方 P——这体现了信号量“一个原语兼具互斥与同步”的威力，但也正因语义复合，信号量程序容易写出 V/P 失配、死锁等隐蔽错误，且分散在各进程中的 P/V 使正确性推理困难。管程(monitor)(Hoare 与 Brinch Hansen,1973)将共享数据与其上的操作封装成一个模块，任一时刻只允许一个进程在管程内活动——互斥由编译器/运行时自动保证，程序员免于手工 P/V;条件不满足时通过条件变量上的 wait(释放管程锁并睡眠)与 signal(唤醒一个等待者)表达同步，信号语义又有 Hoare 语义(立即切换)与 Mesa 语义(唤醒者继续、被唤醒者重新竞争，必须用 while 循环重查条件)之分，Java 的 synchronized/wait/notify、POSIX 的 pthread_mutex + pthread_cond 即是管程思想的工程化。条件变量与互斥锁的组合是构建“等待某条件成立”的标准件。

### 4.3 经典同步问题与无锁结构

几个经典问题沉淀了同步思维：生产者—消费者(有界缓冲)：缓冲区访问需互斥，槽位与产品的计数需两个资源信号量 empty/full,三个信号量的 P 顺序有讲究——先 P 资源后 P 互斥，顺序颠倒即可能死锁，此问题对应现实的管道、消息队列、线程池任务队列。读者—写者问题：允许多读者并发、写者独占，读者优先会让写者饥饿，写者优先又可能饿死读者，公平解法按到达顺序把关。哲学家进餐问题(Dijkstra):五人五叉五意面，朴素的“各取左右叉”会造成人手一叉的循环等待死锁，解法有仅允许四人同时入座、奇偶号哲学家取叉顺序相反、非对称地让一人谦让、或以原子操作同时取两叉，该问题的价值在于揭示死锁的循环等待结构与多种打破手段。此外，屏障(barrier) 用于阶段式并行计算的分阶段汇合，读写锁、顺序锁(RCU,读—复制—更新) 服务于读多写少场景，RCU 更允许读者完全无锁地遍历，写者复制修改后延迟回收旧版本，是 Linux 内核高性能读侧的支柱。CAS 原语还催生了用户态的无锁(lock-free)数据结构与 ABA 问题及其带版本号指针的解法。

## 第五章 死锁

### 5.1 死锁的定义与四条件

死锁(deadlock)是一组进程因争夺资源而互相等待，各进程都被阻塞，若无外力干预永不能推进。1971 年 Coffman 等指出死锁发生的四个必要条件，缺一不可：互斥(资源一次只能被一个进程占有)、占有并等待(进程占有资源又去申请新资源，期间不释放已有)、不可剥夺(已获资源不能被强行抢走，只能自愿释放)、循环等待(存在进程—资源的环形等待链，P0 等 P1 占的资源，P1 等 P2……Pn 等 P0)。注意循环等待是死锁的必要条件，但在“每类资源单实例”情形下它才是充分条件；有单实例资源的循环等待对应资源分配图中的环路。活锁(livelock)是另一种失败形态：进程不阻塞却在无意义地反复改变状态(如走廊里两人互相让路又互相挡路)；饥饿则是调度层面某进程无限期得不到服务，与死锁的区别在于他人仍在正常推进。

### 5.2 死锁的处理策略

策略一：预防(prevention)——静态破坏四条件之一。 破坏互斥：把独占资源改造为共享(如 SPOOLing 技术把打印机虚拟为共享打印队列)，但许多资源本质不可共享。破坏占有并等待：一次性申请全部所需资源，简单可靠但资源利用率低、编程困难(须预知全部需求)。破坏不可剥夺：申请不到新资源就释放已持有资源，或由内核强抢——只适合易保存恢复的资源(如 CPU、内存)，对磁带机等不适用，且实现复杂、开销大、可能活锁。破坏循环等待：给资源类全序编号，规定只能按序申请(如先文件后打印机)，可证明无环即无死锁，编程纪律要求高但被数据库、内核广泛采用。预防手段共性是保守，牺牲并发度与资源利用率。

策略二：避免(avoidance)——动态检查，代表是银行家算法。 与预防不同，避免并不事先施加严格限制，而是在每次分配时判断“分配后系统是否仍处于安全状态”。安全状态指存在某个进程序列，使每个进程依次都能获得其最大需求并完成，从而归还资源让后续进程运行完毕。Dijkstra 的银行家算法模拟银行放贷：维护可用向量、最大需求矩阵、分配矩阵、需求矩阵，试探性分配后用安全性算法寻找安全序列，找得到才真正分配。银行家算法理论优美，但要求进程预先声明最大需求、进程数与资源数固定、资源不会被意外剥夺——这些假设在通用系统中难以成立，故多见于教科书与某些数据库系统，通用 OS 较少采用。

策略三：检测与恢复。 允许死锁发生，但系统周期性地运行死锁检测算法(化简资源分配图：找既不阻塞又非独立的进程，令其运行完毕并释放资源，如此迭代；若所有进程可归入序列则无死锁，剩余者即死锁集)。检测到死锁后的恢复手段：剥夺资源(从受害者抢走给他人)、撤销进程(最简单粗暴，可全部撤销或按代价最小原则逐个撤销直到环路打破)、回滚(借助检查点将进程回卷到安全状态，事务数据库即此思路)。代价函数可考虑进程优先级、已运行时间、剩余时间、已用资源、是否交互式等。

策略四：鸵鸟算法(ostrich algorithm)。 权衡处理死锁的代价与死锁实际发生频率和危害，多数通用操作系统(Linux、Windows)对死锁基本采取无视态度——万一发生便交由管理员或用户重启进程。这在工程上是理性的：发生概率极低、预防/避免的开销与不便远高于偶发重启的损失。但在数据库、嵌入式实时等高可靠系统里绝不可行，两阶段锁协议下的数据库就频繁需要依赖死锁检测与回滚。

## 第六章 内存管理

### 6.1 从物理地址到虚拟地址

程序直接使用物理地址会带来三个问题：所有程序共享一个地址空间，须静态划分互不重叠的重定位区，装载位置不灵活；进程地址空间无法超过物理内存，也无法隔离；多道程序下一个进程可以寻址甚至破坏他人内存。现代操作系统在硬件 MMU(内存管理单元)的配合下引入地址空间抽象：每个进程拥有独立、连续、从 0 开始的虚拟地址空间(32 位为 4GB,64 位通常 48 位有效)，运行时由 MMU 将虚拟地址动态翻译为物理地址。这一抽象带来革命性收益：保护(未经映射的地址不可访问，进程之间天然隔离，内核区受特权级保护)、便利(链接器可假定标准布局；分配只需连续的虚拟空间，不必连续的物理内存)、共享(多个虚拟页可映射同一物理页，实现共享库与 fork 的写时复制)、超额(配合换页，总需求可超物理内存)。翻译本身需要一层间接：动态重定位/基址限长寄存器是最原始的 MMU;分段与分页是两大主流方案。

### 6.2 连续分配与分段

早期采用连续分配：固定分区(把内存划成固定大小分区，有内部碎片)、动态分区(按需切割，常见首次适应、最佳适应、最差适应算法，产生外部碎片，可用紧缩compaction合并但代价巨大，故分配算法的碎片行为是关键——首次适应通常综合最优)。分段(segmentation) 把程序按逻辑意义划分为代码段、数据段、栈段等，每段由(段号，段内偏移)编址，段表记录每段基址与限长，支持按段保护与共享，段大小可变导致仍存在外部碎片。x86 曾有真实的段机制(段寄存器+描述符表)，现代 64 位模式下基本退化。分段对应了程序的逻辑结构，分页则纯粹面向物理管理的便利，两者最终融合为段页式：先分段再分页，兼得语义清晰与物理高效。

### 6.3 分页与虚拟内存

分页(paging) 把虚拟地址空间与物理内存切成固定大小的页(page) 与页帧(frame)(常见 4KB),页表记录“虚页→物理帧”的映射及保护位、有效位、脏位、访问位。地址翻译 = 页号查表得帧号 + 页内偏移。固定大小消除了外部碎片(任何空闲帧都能装任何页)，但单个进程平均损失半页的内部碎片。两个现实难题：一是页表本身过大——32 位/4KB 需百万表项，直接单级表占 4MB,故采用多级页表(未使用的区域不分配次级表，稀疏地址空间下大幅省内存，x86-64 用 4 级、现有 5 级)或倒排页表(按帧索引，省空间但查找需哈希)；二是翻译次数太多，故引入 TLB(翻译后备缓冲，一个针对页表项的小而快的联想缓存)，命中则一次访存完成翻译，命中率因局部性可达 99% 以上，TLB 也是上下文切换必须处理的对象(冲刷或用地址空间标识符 ASID 标记)。

虚拟内存(virtual memory) 是分页 + 磁盘交换的合体：进程映像不必全部驻留内存，有效位为 0 的页触发缺页异常(page fault),内核从磁盘调入(必要时先换出别的页腾出帧)。驻留集管理与置换算法决定换谁：OPT(未来最远使用，不可实现的理论下界)、FIFO(简单，有 Belady 异常——增加帧数反而缺页更多)、LRU(最近最少使用，利用栈式局部性无异常，精确实现代价大)、时钟/CLOCK(二次机会)算法(循环扫描访问位，近似 LRU,工程主流)，以及工作集模型(根据局部性窗口决定驻留量)与缺页频率 PFF 控制。颠簸/抖动(thrashing) 是内存不足的灾难：驻留集太小导致不断缺页，系统忙于换页而无暇计算，总 CPU 利用率反而骤降，解法是挂起部分进程、降低多道程序度、增加内存或改进局部性。写时复制(COW)页与内存映射文件 mmap 是分页机制的两大衍生红利：COW 让 fork 只复制页表，写时才复制页，父子共享只读页；mmap 让文件如同数组般直接访问，页缓存与进程地址空间合二为一，是数据库与动态链接器性能的基石。

## 第七章 文件系统

### 7.1 文件与目录

文件(file) 是具有符号名的一组相关信息的集合，是操作系统提供给用户的最基本抽象：对存储设备的字节序列(块序列)施加名字、权限、元数据的包装。文件的属性(元数据)包括名称、类型、大小、属主、时间戳(atime/mtime/ctime)、权限位(rwx×属主/组/其他)、链接计数等，在 UNIX 中集中存放于** inode**(索引节点)，inode 与文件名解耦——文件名只是目录里指向 inode 编号的一条记录，这正是硬链接(多个名字指向同一 inode,链接计数归零才真正删除)与符号链接(独立小文件存目标路径，可跨文件系统、可悬垂)的原理基础。目录(directory) 是特殊文件，内容是〈名字，inode 号〉的有序表，组织成树(UNIX 单根树，一切皆文件，设备在 /dev、进程信息在 /proc)或森林(Windows 盘符)，路径解析沿目录逐级查名，内核用 dcache(目录项缓存)加速。文件系统还需维护空闲空间(位图或空闲链表)与一致性——突然断电时“元数据已写、数据未写”或位图与 inode 不一致会损毁文件系统，故有 fsck 事后扫描与日志(journaling) 事前记录两种路线：ext3/ext4、NTFS 采用物理日志(WAL 先写意图后写数据，崩溃后重放或回滚)，XFS/ZFS 采用写时复制(从不覆写，新数据写好后再原子切换根指针，天然一致还能快照)。ZFS、btrfs 进一步将卷管理与文件系统、校验和、去重、RAID 融合。

### 7.2 文件的组织与实现

文件的逻辑结构(流式/记录式)与物理结构(连续、链接、索引)由文件系统决定。连续分配(FAT 之前的古典方式)支持随机访问与快速顺序读，但扩展困难、外部碎片；链接分配(FAT 表：每块存下一块指针，表常驻内存)顺序友好无外碎片，随机访问需顺链慢行，指针还占空间；索引分配(UNIX inode:直接块指针 + 一级/二级/三级间接块指针，按文件大小渐进扩展间接层级)兼顾随机与顺序，访问特大文件时多级间接仍嫌慢，故现代系统有区段(extent)化趋势——用〈起始块，长度〉的区段替代逐块指针，大文件元数据更小、访问更快；ext4、XFS、NTFS 均以区段为主。空闲空间管理用位图最普遍，配合区段信息可快速找到连续空闲区。性能优化上，页缓存/缓冲区缓存以 LRU 缓存磁盘块，预读(read-ahead) 顺序访问时提前读入后续块，延迟分配与成簇写聚合随机写为顺序写，这些策略对吞吐影响常常超过数据结构本身。

### 7.3 磁盘调度

机械硬盘的访问时间 = 寻道时间(磁臂移动，毫秒级，主导项)+ 旋转延迟(平均半圈，几毫秒)+ 传输时间(微秒级)，减少磁臂移动是关键。经典磁盘调度算法：FCFS 公平但磁臂乱窜；SSTF(最短寻道优先)贪心，吞吐高但远端请求饥饿；SCAN/电梯算法磁臂单向往返扫描，兼顾效率与公平，是工业基础；C-SCAN 单向扫描到底后快速回程，分布更均匀；LOOK/C-LOOK 不走到物理边界而在最远请求处折返，省去空扫。现代设备层面：硬盘内部缓存、NCQ 原生队列命令让部分调度下推到固件；SSD 没有磁头，随机读性能大增但覆盖写昂贵(须按页写、按块擦)，需要 FTL 闪存转换层做磨损均衡、垃圾回收与写入放大控制，主机侧则发展出 TRIM 指令让文件系统告知哪些块已无效。操作系统磁盘调度器(Linux 的 none/mq-deadline、bfq、kyber)也随之面向多队列与 SSD 重新设计。

## 第八章 输入输出系统

### 8.1 I/O 硬件原理与控制方式

I/O 设备按用途分人机接口(键盘、显示)、存储(磁盘、SSD、磁带)、通信(网卡、串口)；按信息交换单位分块设备(可随机寻址固定块，如磁盘)与字符设备(字节流，如键盘、打印机)。设备一般通过设备控制器接入总线，控制器内有数据寄存器、状态寄存器、控制寄存器；CPU 与控制器沟通有几种方式：程序直接控制/轮询(CPU 反复读状态位，忙等浪费严重，仅适合简单嵌入式)；中断驱动(CPU 发出命令后去做别的事，设备完成后经中断控制器向 CPU 发中断，CPU 保存现场转入中断服务程序 ISR 处理；事件驱动、并发度高，但每个字节一次中断对高速设备开销仍大)；DMA(直接存储器存取)(CPU 只须给 DMA 控制器设定源、目的、长度，控制器自行在设备与内存间搬运整块数据，完成后一次中断通知，CPU 干预降到每块一次，广泛用于磁盘、网卡)。理解中断的处理流程——关中断保存现场、识别中断源、执行 ISR、恢复现场开中断——以及中断的分级与屏蔽，是理解操作系统“事件驱动”本质的关键。

### 8.2 I/O 软件层次与设备无关性

I/O 软件的设计目标是设备无关性(统一接口，应用程序无须为换一台打印机改代码)、统一命名(名字到设备的映射，如 /dev/sda)、错误处理尽量下沉到最贴近硬件的层、以及缓冲与共享管理。经典分层自下而上：中断处理程序(最底层，尽量短小，把主要工作推迟)、设备驱动程序(内核中唯一懂设备细节的模块，将上层的抽象请求翻译为控制器操作)、设备无关软件(命名、保护、缓冲、分配、设备无关块大小)、用户层软件(库函数如 stdio 的缓冲、SPOOLing 守护进程)。UNIX “一切皆文件” 将设备暴露为 /dev 下的特殊文件，open/read/write/ioctl/close 统一了接口，ioctl 承载无法映射为读写的控制操作；Linux 在此之上用 VFS(虚拟文件系统)提供统一文件模型(superblock、inode、dentry、file 四对象与操作表)，使 ext4、XFS、NFS、procfs 等可以插件式共存，同一系统调用对不同文件系统透明。缓冲贯穿各层：单缓冲、双缓冲(读写交替)、循环缓冲，目的是平滑速度差、减少中断与 DMA 次数、解决设备间尺寸失配；用户态 stdio 缓冲、内核页缓存、设备缓冲多级叠加，各层职责需要厘清，否则会出现 fflush 语义之类的困惑。高性能 I/O 的现代形态是异步 I/O 与 I/O 多路复用(select/poll/epoll/kqueue/IOCP)——单线程监视成百上千文件描述符的就绪事件，配合非阻塞 I/O 支撑了 Nginx、Redis 等高并发服务；Linux io_uring 则以用户态与内核共享的提交/完成环形队列把系统调用开销也省去，代表了 I/O 接口演化的前沿。

### 8.3 时钟与时钟中断

时钟是特殊却至关重要的设备：可编程间隔定时器按设定频率(典型 100–1000Hz)产生时钟中断，是操作系统节拍的心脏。时钟中断驱动时间片轮转(递减当前进程时间片)、驱动进程/定时器队列(睡眠到期唤醒、软件看门狗)、维持系统时间与运行统计、驱动调度器负载均衡。高精度定时器(hrtimer)与 tickless(动态时钟，无任务时跳过节拍以省电)是现代改进。

## 第九章 保护、安全与虚拟化

### 9.1 保护机制

保护指控制程序、进程或用户对系统资源的访问能力，防止有意无意的越权。经典原则：最小特权(只给完成任务所需的最小权限，如 UNIX 早期 root 全能与现代细粒度 capability 的对比)；机制与策略分离(内核提供通用机制，策略由用户态配置，如 SELinux 的 loadable policy、cgroups 的资源限额)；纵深防御;开放设计与完全仲裁(每次访问都检查，无一例外)。硬件层面，双模式(内核态/用户态)、MMU 地址空间隔离、权限位(页面 rwx、supervisor 位)构成基本防线；软件层面，UNIX 的 uid/gid 与 rwx 位、ACL(访问控制列表)、capabilities(能力，可分割传递的权限句柄，Linux 的文件 capabilities 与 seccomp-bpf 系统调用过滤)、namespaces(UTS/PID/NET/MNT/USER/IPC/CGROUP/Time 等名字空间隔离进程视野)。安全则在保护之上对抗蓄意攻击：内存漏洞防治(栈保护 canary、NX 不可执行、ASLR 地址随机化、SMEP/SMAP、各类加固编译选项)、权限提升防护、审计日志。攻击面与攻击者的博弈推动了形式化验证内核(seL4 约 1 万行 C 代码被数学证明功能正确)、机密计算(TEE 可信执行环境，如 SGX)、沙箱机制。

### 9.2 虚拟化与容器

虚拟化是在一台物理机上运行多个完整操作系统的技术，其理论基础是 Popek 与 Goldberg 1974 年的等价、资源控制、效率三要求：敏感指令必须陷入 Hypervisor。实现方式：全虚拟化(VMM 陷入-模拟敏感指令，二进制翻译辅助，早期 VMware、QEMU)、半虚拟化(客户机内核知情配合，hypercall 代替敏感指令，Xen)、硬件辅助虚拟化(Intel VT-x/AMD-V 的 root/non-root 模式，VMCS 控制结构，VM entry/exit,现代主流)；内存虚拟化用影子页表或硬件 EPT/NPT 两级翻译；I/O 虚拟化有模拟设备、半虚拟化驱动(virtio)、设备直通与 SR-IOV。虚拟机监视器按位置分 Type-1(裸金属，ESXi、Xen、Hyper-V)与 Type-2(寄宿，VirtualBox)。容器则是更轻量的操作系统级虚拟化：不虚拟硬件，只隔离进程——Linux namespaces 提供视图隔离，cgroups 提供资源限额，联合文件系统(overlayfs)提供镜像分层，配合内核共享，容器启停以毫秒计、密度远超虚拟机，代价是隔离强度较弱(共享内核面)。二者常组合使用：云上“虚拟机 + 容器编排(Kubernetes)”构成现代云计算的操作底座。从某种视角看，虚拟机与容器都是“虚拟”特征在更高层次的再现——操作系统抽象机器，虚拟化又把这台机器变成商品。

## 第十章 分布式趋势与操作系统的未来

### 10.1 多核、NUMA 与操作系统演进

单核频率受功耗墙限制后，硬件转向多核与异构。SMT 同时多线程(如超线程)让一个物理核同时跑两个硬件线程以填充流水线空隙，在 Meltdown/Spectre 侧信道阴影下一度被禁用；NUMA 非一致访存架构下内存分属各 socket,本地访存远快于远端，调度器必须 NUMA 感知(优先在数据所在节点调度、内存按节点分配)否则性能塌方；异构计算把 GPU、NPU、DSP、FPGA、加速器纳入统一的内存与执行模型(CXL 总线、cache 一致性互联、统一地址空间)，操作系统需要新的资源描述、内存模型与调度抽象；持久内存模糊内存与存储的边界，文件系统与页缓存体系被重新审视；Rust 进入内核(Linux 6.1 起支持 Rust 写驱动)试图用语言级内存安全治理内核中约七成源自内存错误的漏洞——这是操作系统实现语言的又一次轮回(Burroughs 的 ALGOL、UNIX 的 C 之传统)。

### 10.2 操作系统概念的迁移与泛化

操作系统原理并不止于单机内核。其一，微内核与形式化：seL4 证明了内核可以做小并做对，MINIX 3 默默运行在数亿颗 Intel 芯片的 ME 引擎里；安全关键领域(航空 DO-178、汽车)对验证内核需求日增。其二，分布式系统是“更大号的操作系统”：RPC/消息对应系统调用，分布式锁服务与共识算法(如 Raft/Paxos)对应同步原语，分布式文件系统(GFS)、调度器(Borg/Kubernetes)对应文件与进程管理——Google 的 Borg 论文直言其调度器是“集群操作系统”；CAP、一致性模型、故障检测成为新的“原理课”。其三，单内核的拆与合：Linux 用 eBPF 让用户安全地把小程序注入内核(网络过滤、观测、调度策略)，FUSE 让文件系统搬到用户态，io_uring/异步机制重构 I/O 路径——内核边界正变得可编程、可渗透。其四，面向新负载的特化 OS：数据中心的内核旁路(DPDK/SPDK)、函数计算(以 Firecracker microVM 秒级冷启动支撑 Serverless)、机密计算、实时+AI 混合负载的调度。

### 10.3 结语：回望与展望

回望七十余年，操作系统的演化有一条清晰的主线：在硬件能力与人类需求的双重牵引下，不断寻找抽象与效率的最优点。从批处理到分时，从多道到虚拟内存，从单核到多核再到分布式，每一次跃迁都在回答同样几个根本问题——如何让昂贵的资源被充分共享？如何在共享的同时保证隔离与安全？如何让程序员不必直面硬件的复杂？进程、线程、调度、同步、内存、文件、I/O 这些概念之所以历久弥新，是因为它们是对这些问题的成熟解答，早已沉淀为计算世界的公共语言。今天学习操作系统原理，意义远超“会用一个系统”：理解调度才能理解延迟与吞吐的取舍，理解虚拟内存才能理解性能分析与容器内存语义，理解同步才能写出正确的并发程序，理解 I/O 栈才能理解数据库与网络服务的性能边界。操作系统的未来无疑还会被重写——为异构加速器、为智能负载、为不可想象的规模——但只要计算机仍然是共享的、有限的、不可靠的物理机器，这套关于资源、抽象与控制的原理就不会过时。正如许多教科书扉页所昭示的：操作系统是计算机科学中工程与理论交织最紧密的领域之一，它既是历史，也是未来。

